function normalizeDistrictName(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/district/g, '')
    .replace(/[^a-z]/g, '')
    .trim();
}

// A farmer's land is often registered under a taluk/town name (e.g.
// "Paramakudi") rather than the official revenue district ("Ramanathapuram")
// — GPS reverse-geocoding commonly returns the town, not the district.
// Reuses the same taluk→district resolver agmarknetService.js already built
// for Agmarknet district IDs (including its spelling-variant matching, e.g.
// "Karaikkudi" vs "Karaikudi"), so the two don't drift apart or disagree.
const { resolveTalukDistrict } = require('../services/agmarknetService');

function resolveZone(districtName) {
  const key = normalizeDistrictName(districtName);
  if (DISTRICT_ZONE_MAP[key]) return DISTRICT_ZONE_MAP[key];

  const parentDistrict = resolveTalukDistrict(districtName);
  if (parentDistrict) return DISTRICT_ZONE_MAP[parentDistrict] || null;

  return null;
}

